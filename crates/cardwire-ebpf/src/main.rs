unsafe fn try_tracepoint_exit_getdents64(ctx: TracePointContext) -> Result<i32, i32> {
    // If it's the daemon, we must exit
    match is_cardwired() {
        Some(res) => {
            if res {
                return ReturnCode::SUCCESS;
            }
        }
        None => {
            // This error happen if either the array is not available or the index 0 of the array is
            // empty
            error!(
                &ctx,
                "EBPF is_cardwired() produced an error in tracepoint_exit_getdents64, skipping"
            );
            return ReturnCode::SUCCESS;
        }
    }

    // If the mode is hybrid, we must exit
    match unsafe { is_hybrid() } {
        Some(res) => {
            if res {
                return ReturnCode::SUCCESS;
            }
        }
        None => {
            // This error happen if either the array is not available or the index 0 of the array is
            // empty
            error!(
                &ctx,
                "EBPF is_hybrid() produced an error in tracepoint_exit_getdents64, skipping"
            );
            return ReturnCode::SUCCESS;
        }
    }

    let pid = (bpf_get_current_pid_tgid() >> 32) as u32;
    let dirent_ptr = match unsafe { CW_DIRENT.get(&pid) } {
        Some(ptr) => *ptr as *const linux_dirent64,
        None => return ReturnCode::SUCCESS,
    };

    let retval = match unsafe { ctx.read_at::<i64>(16) } {
        Ok(ret) => ret as u64,
        Err(_) => return ReturnCode::SUCCESS,
    };

    if retval == 0 || retval > 32768 {
        return ReturnCode::SUCCESS;
    }

    // Buffer end = base + bytes written
    let base = dirent_ptr as u64;
    let end = base.wrapping_add(retval);

    let mut dirent_ptr = dirent_ptr;
    let mut prev_ptr: u64 = 0;
    let mut prev_reclen: u16 = 0;
    for _ in 0..512 {
        // Check before reading
        if (dirent_ptr as u64).wrapping_add(core::mem::size_of::<linux_dirent64>() as u64) > end {
            break;
        }

        let dirent = match unsafe { bpf_probe_read_user(dirent_ptr) } {
            Ok(dirent) => dirent,
            Err(_) => break,
        };

        let reclen = dirent.d_reclen;

        // Malformed
        if reclen == 0 || reclen > 512 {
            break;
        }

        let blocked = unsafe { is_inode_blocked(dirent.d_ino) };
        if blocked {
            // We can't hide the first entry
            if prev_ptr != 0 {
                let new_reclen = prev_reclen.wrapping_add(reclen);

                let reclen_ptr = (prev_ptr.wrapping_add(16)) as *mut u16;
                match unsafe { bpf_probe_write_user(reclen_ptr, &new_reclen) } {
                    Ok(_) => {}
                    Err(err) => {
                        error!(&ctx, "failed to write new reclen {}", err);
                        break;
                    }
                };

                prev_reclen = new_reclen;
            }
        } else {
            prev_ptr = dirent_ptr as u64;
            prev_reclen = reclen;
        }

        dirent_ptr = (dirent_ptr as u64).wrapping_add(reclen as u64) as *const linux_dirent64;
    }

    ReturnCode::SUCCESS
}

#[tracepoint]
pub fn tracepoint_sched_process_exec(ctx: TracePointContext) -> u32 {
    match unsafe { try_tracepoint_sched_process_exec(ctx) } {
        Ok(ret) => ret as u32,
        Err(ret) => ret as u32,
    }
}

unsafe fn try_tracepoint_sched_process_exec(ctx: TracePointContext) -> Result<i32, i32> {
    // If it's the daemon, we must exit
    match is_cardwired() {
        Some(res) => {
            if res {
                return ReturnCode::SUCCESS;
            }
        }
        None => {
            // This error happen if either the array is not available or the index 0 of the array is
            // empty
            error!(
                &ctx,
                "EBPF is_cardwired() produced an error in tracepoint_sched_process_exec, skipping"
            );
            return ReturnCode::SUCCESS;
        }
    }

    // Only proceed if we are in smart mode, events are not used when not in smart mode and it would
    // slow down the system for no reason
    if let Some(res) = unsafe { is_smart() }
        && res
    {
        // Reserve byte in the ring buf for the event, return if fail
        let mut ring_buf = match CW_EXEC_EVENTS.reserve(0) {
            Some(ring_buf) => ring_buf,
            // Reservation fail, warn and leave
            None => {
                warn!(&ctx, "failed to reserve bytes for ring_buf: CW_EXEC_EVENTS");
                return ReturnCode::SUCCESS;
            }
        };
        let pid = (bpf_get_current_pid_tgid() >> 32) as u32;

        // We just send the event to userspace
        let event: ExecEvent = ExecEvent { pid };

        // Now submit the event
        ring_buf.write(event);
        ring_buf.submit(0);
    }

    ReturnCode::SUCCESS
}

