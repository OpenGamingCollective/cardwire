#[tracepoint]
pub fn tracepoint_exit_getdents64(ctx: TracePointContext) -> u32 {
    match unsafe { try_tracepoint_exit_getdents64(ctx) } {
        Ok(ret) => ret as u32,
        Err(ret) => ret as u32,
    }
}

unsafe fn try_tracepoint_exit_getdents64(ctx: TracePointContext) -> Result<i32, i32> {
    let tid = bpf_get_current_pid_tgid() as u32;

    // Drain the map up front to avoid a map leak on an early return
    let dirp = unsafe { CW_DIRENT.get(tid) }.copied();
    let _ = CW_DIRENT.remove(tid);

    let Some(dirp) = dirp else {
        return ReturnCode::SUCCESS;
    };

    let retval = match unsafe { ctx.read_at::<i64>(16) } {
        Ok(ret) => ret as u64,
        Err(_) => return ReturnCode::SUCCESS,
    };

    if retval == 0 || retval > 32768 {
        return ReturnCode::SUCCESS;
    }

    let mut scan = ScanCtx {
        dirent_ptr: dirp,
        end: dirp.wrapping_add(retval),
        prev_ptr: 0,
        prev_reclen: 0,
        status: SCAN_OK,
        errno: 0,
    };

    // The callback reference must be transmuted from the fn pointer, never
    // routed through an integer: the relocation that tags it as
    // BPF_PSEUDO_FUNC only survives if the function symbol reaches ld_imm64
    // untouched
    let callback = unsafe {
        core::mem::transmute::<unsafe extern "C" fn(u32, *mut ScanCtx) -> u64, *mut core::ffi::c_void>(
            scan_dirent,
        )
    };
    let scan_ptr: *mut core::ffi::c_void = core::ptr::addr_of_mut!(scan).cast();
    // MAX_DIRENTS covers any buffer the retval guard lets through, a negative
    // return would mean the helper itself rejected the call (EINVAL/E2BIG)
    let loop_ret = unsafe { bpf_loop(MAX_DIRENTS, callback, scan_ptr, 0) };
    if loop_ret < 0 {
        warn!(&ctx, "bpf_loop failed with {}", loop_ret);
    }

    match scan.status {
        SCAN_WRITE_FAILED => {
            error!(&ctx, "failed to write new reclen {}", scan.errno);
            ReturnCode::SUCCESS
        }
        SCAN_READ_FAILED => Err(-1),
        _ => ReturnCode::SUCCESS,
    }
}

#[tracepoint]
pub fn tracepoint_sched_process_exec(ctx: TracePointContext) -> u32 {
    match unsafe { try_tracepoint_sched_process_exec(ctx) } {
        Ok(ret) => ret as u32,
        Err(ret) => ret as u32,
    }
}

unsafe fn try_tracepoint_sched_process_exec(ctx: TracePointContext) -> Result<i32, i32> {
    // First we clean the MAP
    let pid = (bpf_get_current_pid_tgid() >> 32) as u32;
    let _ = CW_ALLOWED_PID.remove(&pid);
    let _ = CW_FORCED_PID.remove(&pid);
    // If it's the daemon, we must exit
    match is_cardwired() {
        Some(res) => {
            if res {
                return ReturnCode::SUCCESS;
            }
        }
        None => {
            // This error happen if either the array is not available or the index 0 of the array is
            // empty
            error!(
                &ctx,
                "EBPF is_cardwired() produced an error in tracepoint_sched_process_exec, skipping"
            );
            return ReturnCode::SUCCESS;
        }
    }
    if is_comm_whitelisted() {
        return ReturnCode::SUCCESS;
    }

    let is_smart = unsafe { is_smart() }.unwrap_or(false);
    let is_manual = unsafe { is_manual() }.unwrap_or(false);

    // Only proceed if we are in smart or manual mode
    if is_smart || is_manual {
        // Reserve byte in the ring buf for the event, return if fail
        let mut ring_buf = match CW_EXEC_EVENTS.reserve(0) {
            Some(ring_buf) => ring_buf,
            // Reservation fail, warn and leave
            None => {
                warn!(&ctx, "failed to reserve bytes for ring_buf: CW_EXEC_EVENTS");
                return ReturnCode::SUCCESS;
            }
        };

        // Determine mode to send
        let mode_u8 = if is_smart { 3 } else { 2 }; // 3 is Smart, 2 is Manual

        // We just send the event to userspace
        let event: ExecEvent = ExecEvent {
            pid,
            mode: mode_u8,
            _padding: [0; 3],
        };

        // Now submit the event
        ring_buf.write(event);
        ring_buf.submit(0);
    }

    ReturnCode::SUCCESS
}

#[tracepoint]
pub fn tracepoint_sched_process_exit(ctx: TracePointContext) -> u32 {
    match unsafe { try_tracepoint_sched_process_exit(ctx) } {
        Ok(ret) => ret as u32,
        Err(ret) => ret as u32,
    }
}

unsafe fn try_tracepoint_sched_process_exit(_ctx: TracePointContext) -> Result<i32, i32> {
    let pid_tgid: u64 = bpf_get_current_pid_tgid();
    let tgid = pid_tgid as u32;
    let pid = (pid_tgid >> 32) as u32;

    // Only process the exit if the main thread is exiting
    if pid != tgid {
        return ReturnCode::SUCCESS;
    }
    // Remove PID from the maps
    let _ = CW_ALLOWED_PID.remove(&pid);
    let _ = CW_FORCED_PID.remove(&pid);

    ReturnCode::SUCCESS
}

