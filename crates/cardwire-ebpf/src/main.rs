// About verifications:
// All hooks must call the verifications functions before reading any ptr and doing actions
// This prevent slowing down the kernel without justification
// Eg. If the system is on hybrid, we do not need to check if the GPU should be hidden, just skip
// the event

// List of current verifications:
// is_cardwired() -> verify if the event was generated by the daemon, if true skip
// is_comm_whitelisted() -> verify if the event was generated by a whitelisted comm, if true skip
// is_hybrid() -> verify if the system is in hybrid, if true skip
// if is_smart() -> verify if the system is in smart, only for sched_process_exec and
//  sched_process_exit, if false skip in these hooks

#[lsm(hook = "file_open")]
pub fn file_open(ctx: LsmContext) -> i32 {
    match unsafe { try_file_open(ctx) } {
        Ok(ret) => ret,
        Err(ret) => ret,
    }
}

unsafe fn try_file_open(ctx: LsmContext) -> Result<i32, i32> {
    // If it's the daemon, we must exit
    match is_cardwired() {
        Some(res) => {
            if res {
                return ReturnCode::SUCCESS;
            }
        }
        None => {
            // This error happen if either the array is not available or the index 0 of the array is
            // empty
            error!(
                &ctx,
                "EBPF is_cardwired() produced an error in file_open, skipping"
            );
            return ReturnCode::SUCCESS;
        }
    }

    // If the mode is hybrid, we must exit
    match unsafe { is_hybrid() } {
        Some(res) => {
            if res {
                return ReturnCode::SUCCESS;
            }
        }
        None => {
            // This error happen if either the array is not available or the index 0 of the array is
            // empty
            error!(
                &ctx,
                "EBPF is_hybrid() produced an error in file_open, skipping"
            );
            return ReturnCode::SUCCESS;
        }
    }

    let d: *mut dentry = unsafe {
        // arg.0 of file_open is a file
        let file_ptr: *const file = ctx.arg(0);
        (*file_ptr).__bindgen_anon_1.f_path.dentry
    };

    // if no dentry, exit
    if d.is_null() {
        return ReturnCode::SUCCESS;
    }

    // Get a mutable ptr to the inode
    let inode_ptr: *mut inode = unsafe { (*d).d_inode };

    if inode_ptr.is_null() {
        return ReturnCode::SUCCESS;
    }
    let inode: u64 = unsafe { (*inode_ptr).i_ino };

    match unsafe { is_inode_blocked(inode) } {
        true => ReturnCode::ENOENT,
        false => ReturnCode::SUCCESS,
    }
}

